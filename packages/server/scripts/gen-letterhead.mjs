// Embeds the AMS letterhead as base64 so any app can draw it without shipping
// files from `public/` or configuring output file tracing.
// Usage: pnpm --filter @workspace/server gen:letterhead
import { readFile, writeFile } from "node:fs/promises";
import { dirname, join } from "node:path";
import { stdout } from "node:process";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const source = join(root, "assets/membrete-ams-carta.pdf");
const target = join(root, "src/pdf/membrete-ams.ts");

const bytes = await readFile(source);
const base64 = bytes.toString("base64");

await writeFile(
  target,
  `// Generated by scripts/gen-letterhead.mjs from assets/membrete-ams-carta.pdf. Do not edit.\n` +
    `export const MEMBRETE_AMS_PDF_BASE64 =\n  "${base64}";\n`,
);

stdout.write(
  `membrete-ams.ts: ${(bytes.length / 1024).toFixed(0)} KB PDF, ${(base64.length / 1024).toFixed(0)} KB base64\n`,
);
